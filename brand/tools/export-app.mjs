// Writes the brand icons into the Android app: res/drawable/ic_mc_*.xml and ui/Icons.kt.
// Run from the repo root:  node brand/tools/export-app.mjs
// The existing Glyph names keep working; every other brand icon gets a Glyph of its own.
import { mkdirSync, writeFileSync, readdirSync, unlinkSync } from 'node:fs';
import { join } from 'node:path';
import { ICONS } from './icons.mjs';
import { iconAndroid, ROOT } from './brandlib.mjs';

const APP = join(ROOT, '..', 'app', 'src', 'main');
const DRAW = join(APP, 'res', 'drawable');
const KT = join(APP, 'kotlin', 'com', 'pocketnode', 'app', 'ui', 'Icons.kt');

// Glyphs the app already uses, mapped to the brand icon that replaces each one.
const LEGACY = {
  Chat: 'chat', Packs: 'packs', Sliders: 'settings', Back: 'back', Chevron: 'forward', Send: 'send', Plus: 'plus', Check: 'check',
  Close: 'close', Alert: 'alert', Phone: 'phone', Plane: 'send', Lock: 'lock', Key: 'key', Server: 'server', Camera: 'camera',
  File: 'file', Mic: 'mic', Search: 'search', Pin: 'pin', More: 'more', MapPin: 'place', Clock: 'clock', Note: 'note', Bolt: 'bolt',
  Battery: 'battery', Calendar: 'calendar', Person: 'profile', Sun: 'sun', Link: 'link',
};
const camel = (n) => n.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase());
const known = new Map(ICONS.map(([n, , , inner]) => [n, inner]));
for (const [g, n] of Object.entries(LEGACY)) if (!known.has(n)) throw new Error(`${g} maps to missing icon ${n}`);
const used = new Set(Object.values(LEGACY));
const extra = ICONS.map(([n]) => n).filter((n) => !used.has(n));

mkdirSync(DRAW, { recursive: true });
for (const f of readdirSync(DRAW)) if (/^ic_mc_.*\.xml$/.test(f)) unlinkSync(join(DRAW, f));
for (const [name, , , inner] of ICONS) writeFileSync(join(DRAW, `ic_mc_${name.replace(/-/g, '_')}.xml`), iconAndroid(inner, { style: 'line' }));

const res = (n) => `R.drawable.ic_mc_${n.replace(/-/g, '_')}`;
const entries = [...Object.entries(LEGACY).map(([g, n]) => `    ${g}(${res(n)})`), ...extra.map((n) => `    ${camel(n)}(${res(n)})`)];
writeFileSync(KT, `package com.pocketnode.app.ui

import androidx.annotation.DrawableRes
import androidx.compose.foundation.Image
import androidx.compose.foundation.layout.size
import androidx.compose.runtime.Composable
import androidx.compose.ui.Modifier
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.ColorFilter
import androidx.compose.ui.res.painterResource
import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp
import com.pocketnode.app.R

// GENERATED by brand/tools/export-app.mjs from brand/tools/icons.mjs. Do not edit by hand:
// change the drawing in the brand tools and run the script again.
/** The icon set. Each entry is a vector drawable drawn on a 24 unit grid with a 2 unit stroke, round caps and joins. */
enum class Glyph(@DrawableRes val res: Int) {
${entries.join(',\n')};
}

/**
 * A line icon in one color. The stroke weight is part of the drawing (2 units of 24), so [weight] is kept only
 * so older call sites still compile; it has no effect.
 */
@Composable
@Suppress("UNUSED_PARAMETER")
fun Icon(glyph: Glyph, tint: Color, modifier: Modifier = Modifier, size: Dp = 24.dp, weight: Float = 2f) {
    Image(painterResource(glyph.res), contentDescription = null, modifier = modifier.size(size), colorFilter = ColorFilter.tint(tint))
}
`);
console.log(`app icons: ${ICONS.length} drawables, ${Object.keys(LEGACY).length + extra.length} glyphs`);
