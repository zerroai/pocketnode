// Builds every generated brand file. Run from the repo root:  node brand/tools/build.mjs
// (first time: cd brand/tools && npm install). Everything it writes lives under brand/.
import { mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { join } from 'node:path';
