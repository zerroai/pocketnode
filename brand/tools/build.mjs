const out = (rel, data) => {
  const p = join(ROOT, rel);
  mkdirSync(join(p, '..'), { recursive: true });
  writeFileSync(p, data);
};
const clean = (rel) => rmSync(join(ROOT, rel), { recursive: true, force: true });

