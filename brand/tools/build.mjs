// ------------------------------------------------------------------ icons
function iconFiles() {
  clean('icons/svg'); clean('icons/png'); clean('icons/android');
  const names = new Set();
  for (const [name] of ICONS) { if (names.has(name)) throw new Error('duplicate icon ' + name); names.add(name); }
  let sprite = '';
  const manifest = [];
  for (const [name, group, tags, inner] of ICONS) {
    manifest.push({ name, group, tags: tags.split(' ') });
    out(`icons/svg/tile/${name}.svg`, tileSvg(inner, 96) + '\n');
    out(`icons/png/tile/${name}.png`, png(tileSvg(inner, 96), 192));
    for (const style of ['line', 'tint']) {
      out(`icons/svg/${style}/${name}.svg`, iconSvg(inner, { style, color: 'currentColor' }) + '\n');
      out(`icons/android/${style}/ic_mc_${name.replace(/-/g, '_')}.xml`, iconAndroid(inner, { style }));
      const symbol = iconSvg(inner, { style, color: 'currentColor' }).replace(/^<svg[^>]*>/, '').replace('</svg>', '');
      sprite += `<symbol id="mc-${name}${style === 'tint' ? '-tint' : ''}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${symbol}</symbol>`;
      for (const [cname, color] of [['black', COLORS.black], ['white', '#FFFFFF'], ['silver', COLORS.silver]]) {
        out(`icons/png/${style}/${cname}/${name}.png`, png(iconSvg(inner, { style, color, size: 96 }), 96));
      }
    }
  }
  out('icons/sprite.svg', `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">${sprite}</svg>\n`);
  out('icons/icons.json', JSON.stringify({ grid: 24, stroke: 2, styles: ['line', 'tint', 'tile'], groups: GROUPS, icons: manifest }, null, 2) + '\n');
  out('icons/icon-names.kt.txt', `// Generated. One entry per drawable ic_mc_<name> in icons/android/line and icons/android/tint.\nenum class McIcon(val res: String) {\n${ICONS.map(([n]) => `    ${n.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase())}("ic_mc_${n.replace(/-/g, '_')}")`).join(',\n')}\n}\n`);
}

