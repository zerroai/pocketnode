  out('app-icon/store/alt-silver-1024.png', png(appIconDepth('silver', 1024, 0), 1024));
  out('app-icon/store/tinted-1024.png', png(appIcon({ bg: '#000000', fg: '#FFFFFF', radius: 0 }), 1024));
  for (const [dir, px] of [['mdpi', 48], ['hdpi', 72], ['xhdpi', 96], ['xxhdpi', 144], ['xxxhdpi', 192]]) {
    out(`app-icon/android/mipmap-${dir}/ic_launcher.png`, png(appIconDepth('black', px, 0.225), px));
    out(`app-icon/android/mipmap-${dir}/ic_launcher_round.png`, png(appIconDepth('black', px, 0.5), px));
  }
  out('app-icon/android/ic_launcher_foreground.xml', androidForeground('#FFD5D8DE', 0.85));
  out('app-icon/android/ic_launcher_monochrome.xml', androidForeground('#FF000000', 0.85));
  out('app-icon/android/ic_launcher_background.xml', `<?xml version="1.0" encoding="utf-8"?>\n<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="108dp"\n    android:height="108dp"\n    android:viewportWidth="108"\n    android:viewportHeight="108">\n    <path android:fillColor="#FF0F1013" android:pathData="M0,0h108v108h-108z" />\n</vector>\n`);
  out('app-icon/android/ic_launcher.xml', `<?xml version="1.0" encoding="utf-8"?>\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n    <background android:drawable="@drawable/ic_launcher_background" />\n    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n</adaptive-icon>\n`);
